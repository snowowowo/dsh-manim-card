/** 方法调用：改写表优先（能翻译的写法），否则按表校验 + 给 manim-web 的真方法名与实参。 */
function planMethod(name, args, kwargs) {
	const rewrite = METHOD_REWRITES[name];
	if (rewrite !== void 0) return { variants: rewrite(args, kwargs) };
	assertSupported(name);
	const mapped = PY_API_MAP[name]?.js;
	const jsName = mapped !== void 0 && IDENTIFIER$1.test(mapped) ? mapped : camel(name);
	const positional = [...args];
	const rest = { ...kwargs };
	const order = POSITIONAL_ARGS[name];
	if (order !== void 0) for (let index = positional.length; index < order.length; index += 1) {
		const value = rest[order[index]];
		if (value === void 0) break;
		positional.push(value);
		delete rest[order[index]];
	}
	const kw = camelKeys(rest);
	return { variants: [[{
		js: jsName,
		args: Object.keys(kw).length > 0 ? [...positional, kw] : positional
	}]] };
}
